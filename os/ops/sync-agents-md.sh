#!/usr/bin/env bash
# Mirror the global ~/.claude/CLAUDE.md into the Codex instruction files so both
# agents run on the same rules: ~/AGENTS.md and ~/.codex/AGENTS.md.
#
# WHY (2026-10-22): the AGENTS.md copies were hand-made once with a blind
# claude->Codex replace, then never refreshed. By October they were 2 weeks stale
# (no Ebda business, a removed MCP still listed) and every `~/.Codex/...` path
# pointed at a file that does not exist — memory, scripts and the playbook live
# under ~/.claude/. So: copy verbatim (paths stay ~/.claude), prepend a header.
#
# Usage:
#   ops/sync-agents-md.sh           # write both targets when they differ
#   ops/sync-agents-md.sh --check   # exit 1 (and list targets) on drift; write nothing
# Run by update-memory-pipeline.sh (all/global scope), non-fatal there.
set -euo pipefail

SRC="${SYNC_AGENTS_SRC:-$HOME/.claude/CLAUDE.md}"
TARGETS=("$HOME/AGENTS.md" "$HOME/.codex/AGENTS.md")
CHECK=0; [ "${1:-}" = "--check" ] && CHECK=1

[ -f "$SRC" ] || { echo "sync-agents-md: source $SRC missing" >&2; exit 2; }

HEADER='<!-- GENERATED by ebda-foundation ops/sync-agents-md.sh from ~/.claude/CLAUDE.md - do not edit here, edit CLAUDE.md. Paths under ~/.claude/ are the REAL locations (memory, scripts, playbook) - do not rewrite them to ~/.codex. Claude-only tools (Agent model routing, Skill, /goal, claude -p) map to the closest Codex equivalent or are skipped. -->'

want="$(mktemp)"; trap 'rm -f "$want"' EXIT
{ printf '%s\n\n' "$HEADER"; cat "$SRC"; } > "$want"

drift=0
for t in "${TARGETS[@]}"; do
  cmp -s "$want" "$t" 2>/dev/null && continue
  drift=1
  if [ "$CHECK" -eq 1 ]; then echo "drift: $t"; continue; fi
  mkdir -p "$(dirname "$t")"
  cp "$want" "$t"
  echo "synced: $t"
done

[ "$CHECK" -eq 1 ] && exit "$drift"
[ "$drift" -eq 0 ] && echo "sync-agents-md: up to date"
exit 0
