#!/usr/bin/env bash
# sync-agents-md: both Codex targets mirror CLAUDE.md verbatim (paths untouched),
# --check reports drift without writing, and a missing source fails loud.
# Fake HOME only; never touches the real files.
set -uo pipefail
cd "$(dirname "$0")/.." || exit 1; OPS="$(pwd)"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
_pass=0; _fail=0
pass() { echo "PASS: $1"; _pass=$((_pass+1)); }
fail() { echo "FAIL: $1"; _fail=$((_fail+1)); }
run() { HOME="$T" bash "$OPS/sync-agents-md.sh" "$@"; }

mkdir -p "$T/.claude"
printf '# rules\nmemory: `~/.claude/projects/x/memory/`\n' > "$T/.claude/CLAUDE.md"

# 1. drift on a fresh HOME: --check exits 1 and writes nothing
run --check >/dev/null; rc=$?
[ "$rc" -eq 1 ] && pass "--check exits 1 on drift" || fail "--check rc=$rc, want 1"
[ ! -e "$T/AGENTS.md" ] && pass "--check wrote nothing" || fail "--check wrote a file"

# 2. sync writes both targets, body verbatim (no ~/.Codex rewrite)
run >/dev/null
for f in "$T/AGENTS.md" "$T/.codex/AGENTS.md"; do
  if tail -n +3 "$f" | cmp -s - "$T/.claude/CLAUDE.md"; then pass "body verbatim: ${f#"$T"/}"; else fail "body differs: ${f#"$T"/}"; fi
done
grep -q '\.Codex' "$T/AGENTS.md" && fail ".Codex path leaked" || pass "no .Codex rewrite"
grep -q 'GENERATED by ebda-foundation' < <(head -1 "$T/AGENTS.md") && pass "header present" || fail "header missing"

# 3. in sync: --check exits 0
run --check >/dev/null && pass "--check exits 0 when in sync" || fail "--check nonzero when in sync"

# 4. a CLAUDE.md edit is picked up
echo "- new rule" >> "$T/.claude/CLAUDE.md"
run >/dev/null
grep -q -- '- new rule' "$T/.codex/AGENTS.md" && pass "edit propagated" || fail "edit not propagated"

# 5. missing source fails loud (exit 2), not a silent no-op
rm "$T/.claude/CLAUDE.md"
run >/dev/null 2>&1; rc=$?
[ "$rc" -eq 2 ] && pass "missing source exits 2" || fail "missing source rc=$rc, want 2"

echo "── $_pass passed, $_fail failed ──"
[ "$_fail" -eq 0 ]
