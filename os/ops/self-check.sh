#!/usr/bin/env bash
# Whisky AI OS — living-foundation self-check + self-map.
# (A) SELF-MAP: regenerate ARCHITECTURE.md — a concise, accurate narrative of
#     what the foundation repo contains and how the parts connect: ops/ scripts,
#     standard/ rubric files, launchd jobs + their cadence, docs/superpowers specs.
# (B) SELF-COHERENCE: flag drift between the repo's own moving parts — broken
#     launchd → script pointers, missing standard/ files, unscheduled scripts, and
#     ops/ scripts referenced in docs but absent on disk.
#
# Usage:
#   ops/self-check.sh            # write ARCHITECTURE.md + print coherence findings
#   ops/self-check.sh --notify   # same + Telegram summary if any ERROR/WARN exists
#
# READ-ONLY except for writing ../ARCHITECTURE.md. Never touches other repos. No git.
# shellcheck source=lib/os-config.sh
. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/os-config.sh" 2>/dev/null || . "$HOME/.claude/scripts/lib/os-config.sh" 2>/dev/null || true
command -v os_config_load >/dev/null 2>&1 && os_config_load
set -uo pipefail
cd "$(dirname "$0")" || exit 1

NOTIFY_FLAG=0
[ "${1:-}" = "--notify" ] && NOTIFY_FLAG=1

REPO="$(cd .. && pwd)"
ARCH="$REPO/ARCHITECTURE.md"

# The lens count is DEFINED by standard/00-index.md's numbered table. Derive it:
# hardcoding drifted once — ARCHITECTURE.md said 20 while the rubric had 29, and
# because this script REGENERATES that file, hand-editing the output could never
# have fixed it. (verify-before-assert: read the source, do not restate it.)
NLENS=$(grep -cE '^\| [0-9]+ \| `[a-z-]+` \|' "$REPO/standard/00-index.md")
[ "${NLENS:-0}" -gt 0 ] || { echo "self-check: could not count lenses in standard/00-index.md" >&2; exit 1; }

# ── helpers ──────────────────────────────────────────────────────────────────

# Script descriptions extracted at runtime — each script's first meaningful
# comment line (the # <desc> after the shebang). Skips separator lines (====)
# and blank comment lines. Takes the first non-separator, non-empty # line.
_script_desc() {
  local f="$1"
  # First meaningful comment line, skipping three things that are NOT a
  # description: separator rules, empty comment lines, and the claude-hook
  # declaration block. That block (added 2026-09-04, bounded by its own
  # `# claude-hook:` line) sits ABOVE the real description in five scripts, so
  # a naive first-line read captions them with hook plumbing.
  #
  # The separator class is `[=*-]` with the dash LAST and no backslashes. It
  # was `[=\-\*]`, where the backslashes are literal inside a bracket
  # expression, making `\-\*` a reversed range so `-` never joined the set —
  # every dashed rule sailed through and five scripts were captioned
  # `------------` in ARCHITECTURE.md. It reads correct, and zsh masks it:
  # reproduce shell bugs in the shell of the shebang.
  awk '
    /^# claude-hook declaration/ { inhook = 1 }
    inhook && /^# claude-hook:/  { inhook = 0; next }
    inhook                       { next }
    /^# claude-hook:/            { next }
    /^# [=*-]{4,}$/              { next }
    /^# ?$/                      { next }
    /^# /                        { sub(/^# */, ""); print; exit }
  ' "$f" 2>/dev/null
}

# Extract first # heading from a markdown file.
_md_heading() {
  grep -m1 '^# ' "$1" 2>/dev/null | sed 's/^# *//'
}

# ── findings arrays ────────────────────────────────────────────────────────
# bash 3.2: plain indexed arrays of strings only.
findings_error=()
findings_warn=()
findings_info=()

add_error() { findings_error+=("ERROR: $1"); }
add_warn()  { findings_warn+=("WARN:  $1"); }
add_info()  { findings_info+=("INFO:  $1"); }

# ── on-demand scripts (not expected to have a plist) ────────────────────────
# These are explicitly on-demand; treat as expected-unscheduled → INFO only.
is_expected_ondemand() {
  case "$1" in
    # core on-demand tools
    notify.sh|blast-radius.sh|propagate.sh|install.sh|safe-to-admin-merge.sh|self-check.sh) return 0 ;;
    # dreaming-cycle phase scripts — called by dream.sh, not directly by launchd
    dream-research.sh|dream-scan.sh|dream-fix.sh|dream-act.sh) return 0 ;;
    # runner-hook tooling — the health-detector is on-demand (alongside ci-runner-guard)
    runner-hook-health.sh) return 0 ;;
    *) return 1 ;;
  esac
}

# ─────────────────────────────────────────────────────────────────────────────
# (A) SELF-MAP — build ARCHITECTURE.md
# ─────────────────────────────────────────────────────────────────────────────

# Repo git date (best-effort; allowed read-only access)
REPO_DATE=""
if command -v git >/dev/null 2>&1; then
  REPO_DATE=$(git -C "$REPO" log -1 --format=%cd --date=short 2>/dev/null || true)
fi

{

cat <<'HDR'
# Ebda Foundation — Architecture

> Auto-generated by `ops/self-check.sh` — regenerated each run. Do not hand-edit.
> NOTE: no timestamp is baked in by default; if you want the last-commit date, read it
> via `git log -1 --format=%cd` of this repo (that is what the generator does).

This document is the **self-map** of the `ebda-foundation` repo: what every file
does, how the parts connect, and what runs on what schedule. It is the first thing a
Claude session (or a human) should read before touching this repo.

---

HDR

# ── repo date line (if available) ──
if [ -n "$REPO_DATE" ]; then
  echo "_Last-commit date: ${REPO_DATE}_"
  echo
fi

# ── ops/ scripts ─────────────────────────────────────────────────────────────
echo "## ops/ — the running OS"
echo
echo "The scripts that MAKE the Whisky AI OS work. \`install.sh\` copies them to"
echo "\`~/.claude/scripts/\` (launchd TCC restriction) and wires the launchd jobs."
echo
echo "| Script | Purpose |"
echo "|--------|---------|"

for f in "$REPO/ops/"*.sh; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  desc=$(_script_desc "$f")
  printf '| `%s` | %s |\n' "$name" "$desc"
done
echo

# ── standard/ rubric ──────────────────────────────────────────────────────────
echo "## standard/ — the gradeable rubric"
echo
echo "${NLENS} concern-files (one per production layer) that form the single Build+Audit"
echo "rubric. \`unified-audit.md\` is the entry point for an audit run. Grade scale:"
echo "\`0\` = absent · \`1\` = partial · \`2\` = solid."
echo
echo "| File | Heading |"
echo "|------|---------|"

for f in "$REPO/standard/"*.md; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  heading=$(_md_heading "$f")
  printf '| `%s` | %s |\n' "$name" "$heading"
done
echo

# ── launchd — scheduled jobs ──────────────────────────────────────────────────
echo "## launchd — what's scheduled"
echo
echo "Plists live in \`ops/launchd/\`. \`install.sh\` loads them into"
echo "\`~/Library/LaunchAgents\` (copies scripts first to \`~/.claude/scripts/\`)."
echo "Note: some plists point at \`~/.claude/scripts/\` (the installed copy); the"
echo "canonical source is always \`ops/\`."
echo
echo "| Label | Cadence | Script invoked |"
echo "|-------|---------|----------------|"

for plist in "$REPO/ops/launchd/"*.plist; do
  [ -f "$plist" ] || continue
  python3 -c "
import plistlib, sys, os

with open(sys.argv[1], 'rb') as fh:
    d = plistlib.load(fh)

label = d.get('Label', '?')
args  = d.get('ProgramArguments', d.get('Program', []))
if isinstance(args, list):
    script = ' '.join(args)
else:
    script = str(args)

si  = d.get('StartInterval', None)
sci = d.get('StartCalendarInterval', None)

if si:
    mins = int(si) // 60
    cadence = 'every %dm' % mins if mins < 60 else 'every %dh' % (mins // 60)
elif sci:
    if isinstance(sci, dict):
        parts = []
        if 'Weekday' in sci:
            days = ['Sun','Mon','Tue','Wed','Thu','Fri','Sat']
            parts.append(days[sci['Weekday']] if sci['Weekday'] < len(days) else str(sci['Weekday']))
        if 'Hour' in sci and 'Minute' in sci:
            parts.append('%02d:%02d' % (sci['Hour'], sci['Minute']))
        cadence = ' '.join(parts) if parts else str(sci)
    else:
        cadence = str(sci)
else:
    cadence = '(no schedule set)'

print('| \`%s\` | %s | \`%s\` |' % (label, cadence, script))
" "$plist"
done
echo

# ── docs/ — specs + plans ──────────────────────────────────────────────────
echo "## docs/ — specs, plans, and reference"
echo
echo "| File | Path |"
echo "|------|------|"

find "$REPO/docs" -type f -name "*.md" | sort | while IFS= read -r f; do
  rel="${f#$REPO/}"
  heading=$(_md_heading "$f")
  if [ -z "$heading" ]; then heading=$(basename "$f" .md); fi
  printf '| %s | `%s` |\n' "$heading" "$rel"
done
echo

# ── how the parts connect ────────────────────────────────────────────────────
cat <<'CONNECT' | sed "s/@NLENS@/${NLENS}/g"
## How the parts connect

```
standard/00-index.md           ← the rubric index; defines @NLENS@ concern IDs
  └─ standard/<id>.md          ← one per concern (grading criteria)
       └─ unified-audit.md     ← entry point for an audit run; blends all @NLENS@ lenses

ops/install.sh                 ← one-time setup: copies scripts + loads launchd
  └─ ops/launchd/*.plist       ← schedule definitions (point at ~/.claude/scripts/)
       └─ ops/*.sh             ← the OS runtime (source; installed copies are live)

ops/notify.sh                  ← universal Telegram primitive; all scripts use it
ops/os-watch.sh                ← git/CI delivery state across all Force repos (scheduled)
ops/alert-triage.sh            ← reads Sentry/UptimeRobot/Railway/Gmail/CI (scheduled)
ops/anomaly-watch.sh           ← post-deploy anomaly detection (scheduled)
ops/checkout-monitor.sh        ← synthetic checkout-path smoke test (scheduled)
ops/docs-scan.sh               ← structural doc-drift detector across prod repos (scheduled)
ops/blast-radius.sh            ← graphify-driven PR blast-radius reviewer (on-demand)
ops/propagate.sh               ← cross-repo change propagation engine (on-demand)
ops/safe-to-admin-merge.sh     ← gate before any admin-merge; checks security checks (on-demand)
ops/msg-monitor.sh             ← whatsapp liveness + authenticated login/me correctness probe (scheduled)
ops/ci-runner-guard.sh         ← bidirectional runner guard: cloud-exhaustion↔self-hosted saturation (scheduled)
ops/deploy-drift.sh            ← prod deploy-freshness check vs main HEAD per service (scheduled)
ops/self-check.sh              ← this script; regenerates ARCHITECTURE.md + coherence check (on-demand)

docs/superpowers/specs/        ← design + architecture specs
docs/superpowers/plans/        ← implementation plans
docs/SERVICE-TOKENS.md         ← token/credential setup reference
docs/blast-radius-reviewer.md  ← blast-radius reviewer design doc
```
CONNECT

} > "$ARCH"

echo "[self-check] wrote ARCHITECTURE.md"

# ─────────────────────────────────────────────────────────────────────────────
# (B) SELF-COHERENCE CHECKS
# ─────────────────────────────────────────────────────────────────────────────

# ── Check 1: ops/*.sh with no launchd plist referencing it ───────────────────
for f in "$REPO/ops/"*.sh; do
  [ -f "$f" ] || continue
  name=$(basename "$f")
  if is_expected_ondemand "$name"; then
    add_info "$name: on-demand (no plist expected)"
    continue
  fi
  # Search for any plist that mentions this script name (either ops/ or ~/.claude/scripts/)
  base="${name%.sh}"
  if grep -rl "$name" "$REPO/ops/launchd/" >/dev/null 2>&1; then
    : # scheduled
  elif grep -rl "$base" "$REPO/ops/launchd/" >/dev/null 2>&1; then
    : # scheduled by base name
  else
    add_info "$name: not referenced by any plist (may be on-demand or not yet scheduled)"
  fi
done

# ── Check 2: launchd plist → script path that does NOT exist on disk ──────────
for plist in "$REPO/ops/launchd/"*.plist; do
  [ -f "$plist" ] || continue
  label=$(basename "$plist")
  # Collect missing paths via python3 into a variable (avoids pipe-subshell for add_error)
  missing_list=$(python3 -c "
import plistlib, sys, os

plist_path = sys.argv[1]
with open(plist_path, 'rb') as fh:
    d = plistlib.load(fh)

args = d.get('ProgramArguments', d.get('Program', []))
if isinstance(args, list):
    paths = [a for a in args if '/' in a and not a.startswith('-')]
elif isinstance(args, str) and '/' in args:
    paths = [args]
else:
    paths = []

home = os.path.expanduser('~')
for p in paths:
    # ops/launchd/*.plist are TEMPLATES: install.sh expands __HOME__ at install
    # time. Test the expanded path, or every template errors as 'non-existent
    # script' (41 false ERRORs on 2026-08-14, burying the real warnings).
    if not os.path.isfile(p.replace('__HOME__', home)):
        print(p)
" "$plist" 2>/dev/null)
  if [ -n "$missing_list" ]; then
    while IFS= read -r missing; do
      [ -n "$missing" ] && add_error "$label: plist points to non-existent script: $missing"
    done <<EOF_MISSING
$missing_list
EOF_MISSING
  fi
done

# ── Check 2.5: launchd plist execs from a TCC-protected dir (Desktop/Documents/Downloads) ──
# macOS TCC blocks launchd from exec'ing scripts under these folders → the job
# silently fails every interval with "Operation not permitted". This killed the
# checkout-monitor / alert-triage / anomaly-watch / dream jobs (2026-06-10).
# Runnable copies MUST live in ~/.claude/scripts (non-protected). Scan BOTH the
# repo templates AND the installed plists so a regression is caught either side.
for plist in "$REPO/ops/launchd/"*.plist "$HOME/Library/LaunchAgents/${OS_LAUNCHD_PREFIX}."*.plist; do
  [ -f "$plist" ] || continue
  label=$(basename "$plist")
  tcc_hit=$(python3 -c "
import plistlib, sys, re
with open(sys.argv[1], 'rb') as fh:
    d = plistlib.load(fh)
args = d.get('ProgramArguments', d.get('Program', []))
paths = [a for a in (args if isinstance(args, list) else [args]) if isinstance(a, str) and a.endswith('.sh')]
prot = re.compile(r'/(Desktop|Documents|Downloads)/')
for p in paths:
    if prot.search(p):
        print(p)
" "$plist" 2>/dev/null)
  if [ -n "$tcc_hit" ]; then
    while IFS= read -r hit; do
      [ -n "$hit" ] && add_error "$label: execs from TCC-protected path (launchd will be blocked): $hit — move the runnable copy to ~/.claude/scripts"
    done <<EOF_TCC
$tcc_hit
EOF_TCC
  fi
done

# ── Check 3: standard/<id>.md in 00-index.md but missing on disk, and vice versa ──
INDEX="$REPO/standard/00-index.md"

# IDs the index "knows about": the 20 numbered lens rows (| 1 | `architecture` | ...)
# PLUS any cross-cutting doc referenced in prose as a backtick filename
# (e.g. `unified-audit.md`). The latter covers docs that are part of the
# standard but are not one of the 20 graded lenses.
INDEX_IDS=$(python3 -c "
import re, sys
text = open(sys.argv[1]).read()
ids = re.findall(r'\|\s*\d+\s*\|\s*\x60([a-z][a-z0-9_-]*)\x60', text)
# also accept backtick-quoted '<name>.md' DEFINITION lines ('- \x60name.md\x60 — ...').
# Anchored to the list-item start: an inline prose mention (e.g. 'a \x60handoff.md\x60
# at each repo root' inside session-handoff's description) names a per-repo
# artifact, not a standard, and must not be required to exist in standard/.
ids += [m[:-3] for m in re.findall(r'^\s*[-*>]\s*\x60([a-z][a-z0-9_-]*\.md)\x60', text, re.M)]
print('\n'.join(sorted(set(ids))))
" "$INDEX" 2>/dev/null)

# IDs on disk (filename without .md, skip 00-index itself)
DISK_IDS=$(for f in "$REPO/standard/"*.md; do
  name=$(basename "$f" .md)
  if [ "$name" != "00-index" ]; then echo "$name"; fi
done)

# IDs in index but not on disk
for id in $INDEX_IDS; do
  found=0
  for disk_id in $DISK_IDS; do
    [ "$id" = "$disk_id" ] && found=1 && break
  done
  [ "$found" = "0" ] && add_error "standard/$id.md: listed in 00-index.md but MISSING on disk"
done

# IDs on disk but not in index
for disk_id in $DISK_IDS; do
  found=0
  for id in $INDEX_IDS; do
    [ "$id" = "$disk_id" ] && found=1 && break
  done
  [ "$found" = "0" ] && add_warn "standard/$disk_id.md: on disk but NOT mentioned in 00-index.md"
done

# ── Check 4: ops/<name>.sh referenced in standard/*.md or README.md but absent ──
# Collect all ops/X.sh references from standard/ + README.md
REFERENCED=$(grep -roh 'ops/[a-zA-Z_-]*\.sh' "$REPO/standard/" "$REPO/README.md" 2>/dev/null \
  | sed 's|.*/||' | sort -u)

for ref in $REFERENCED; do
  [ -f "$REPO/ops/$ref" ] || add_warn "ops/$ref: referenced in docs/standard but does not exist on disk"
done

# ─────────────────────────────────────────────────────────────────────────────
# Print coherence report
# ─────────────────────────────────────────────────────────────────────────────

echo
echo "=== SELF-COHERENCE FINDINGS ==="
echo

total_errors=${#findings_error[@]}
total_warns=${#findings_warn[@]}
total_infos=${#findings_info[@]}

if [ "$total_errors" -gt 0 ]; then
  for f in ${findings_error[@]+"${findings_error[@]}"}; do echo "  $f"; done
fi
if [ "$total_warns" -gt 0 ]; then
  for f in ${findings_warn[@]+"${findings_warn[@]}"}; do echo "  $f"; done
fi
if [ "$total_infos" -gt 0 ]; then
  for f in ${findings_info[@]+"${findings_info[@]}"}; do echo "  $f"; done
fi

if [ "$total_errors" -eq 0 ] && [ "$total_warns" -eq 0 ]; then
  echo "  No ERROR or WARN findings. $(( total_infos )) INFO item(s) (on-demand/scheduling notes)."
else
  echo
  echo "  Summary: ${total_errors} ERROR(s), ${total_warns} WARN(s), ${total_infos} INFO(s)"
fi

# ── Optional Telegram notify ─────────────────────────────────────────────────
if [ "$NOTIFY_FLAG" = "1" ] && [ $(( total_errors + total_warns )) -gt 0 ]; then
  lines=""
  for f in ${findings_error[@]+"${findings_error[@]}"}; do lines="${lines}  • $f"$'\n'; done
  for f in ${findings_warn[@]+"${findings_warn[@]}"};  do lines="${lines}  • $f"$'\n'; done
  msg="Self-check: ${total_errors} ERROR(s), ${total_warns} WARN(s) in ebda-foundation"$'\n'"${lines}"
  if [ -x "./notify.sh" ]; then
    ./notify.sh "Self-check" "$msg" >/dev/null 2>&1 || true
  fi
fi

# Exit non-zero if there are ERRORs (makes CI integration easy)
[ "$total_errors" -eq 0 ]
